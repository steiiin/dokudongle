export {}

const modal = () => cy.get('ion-modal:visible')
const group = (label: string) => modal().find(`[role="group"][aria-label="${label}"]`)
const chip = (label: string, text: string) => group(label).contains('ion-chip', new RegExp(`^(?:✓\\s*)?${text}$`))
const close = () => {
  modal().find('ion-header ion-button').click()
  cy.get('ion-modal:visible').should('not.exist')
}
const stSelect = (direction: string) => modal().contains('.dd-input-select-chips', `ST-${direction}`)
const leadDialog = () => cy.get('ion-modal.dd-input-select-chips-modal:visible')
const leadChip = (lead: string) => leadDialog().contains('button', new RegExp(`^\\s*${lead}\\s*$`))
const applyLeads = () => {
  leadDialog().contains('ion-button', 'Übernehmen').click()
  leadDialog().should('not.exist')
}
const selectLeads = (direction: string, leads: string[]) => {
  stSelect(direction).scrollIntoView().click()
  for (const lead of leads) leadChip(lead).scrollIntoView().click()
  applyLeads()
}
const activate = () => cy.get('[data-examination="ecg"] .activate-examination').click()
const frequency = () => modal().find('ion-range.ecg-frequency')
const frequencyTitle = () => modal().find('.ecg-input ion-item-divider').last()
const pressKey = (key: 'Enter' | ' ' | 'Escape' | 'ArrowRight' | 'ArrowLeft') => {
  const params = { key, code: key === ' ' ? 'Space' : key, windowsVirtualKeyCode: { Enter: 13, ' ': 32, Escape: 27, ArrowRight: 39, ArrowLeft: 37 }[key] }
  return cy.then(() => Cypress.automation('remote:debugger:protocol', {
    command: 'Input.dispatchKeyEvent', params: { ...params, type: 'keyDown', text: key === 'Enter' ? '\r' : key === ' ' ? ' ' : undefined },
  })).then(() => Cypress.automation('remote:debugger:protocol', {
    command: 'Input.dispatchKeyEvent', params: { ...params, type: 'keyUp' },
  }))
}

for (const mode of ['md', 'ios']) {
  describe(`ECG chips (${mode})`, () => {
    beforeEach(() => {
      cy.viewport(390, 844)
      cy.visit(`/tests/e2e/fixtures/examination.html?circulation&mode=${mode}`)
      activate()
    })

    it('shows frequency last, omits untouched presets and preserves entered single values', () => {
      frequency().should('not.exist')
      chip('Eingrenzen', 'Brady').click()
      frequencyTitle().should('have.text', 'Frequenz: 50/min')
      frequency().should('have.prop', 'min', 5).and('have.prop', 'max', 55)
        .and('have.prop', 'step', 5).and('have.prop', 'snaps', true).and('have.prop', 'pin', true)
        .and('have.prop', 'dualKnobs', false)
      close()
      cy.get('#report').should('contain.text', 'Sinusbradyk').and('not.contain.text', '/min')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').click()
      frequency().scrollIntoView().shadow().find('[role="slider"]').should('have.length', 1)
        .and('have.attr', 'aria-label', 'Frequenz in Schlägen pro Minute').focus()
      pressKey('ArrowLeft')
      frequencyTitle().should('have.text', 'Frequenz: 45/min')
      close()
      cy.get('#report').should('contain.text', '45/min')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').click()
      frequencyTitle().should('have.text', 'Frequenz: 45/min')
      chip('Extrasystolen', 'VES').scrollIntoView().click()
      frequency().should('have.prop', 'dualKnobs', false).and('have.prop', 'value', 45)
      chip('Eingrenzen', 'Tachy').scrollIntoView().click()
      frequencyTitle().should('have.text', 'Frequenz: 150/min')
      frequency().should('have.prop', 'min', 105).and('have.prop', 'max', 300)
      close()
      cy.get('#report').should('not.contain.text', '/min')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').click()
      chip('Eingrenzen', 'Normo').click()
      frequency().should('not.exist')
    })

    it('adjusts both frequency knobs in five-unit steps and clears hidden values', () => {
      cy.viewport(320, 720)
      chip('Grundrhythmus', 'Vorhofflimmern').click()
      chip('Eingrenzen', 'Brady').click()
      frequencyTitle().should('have.text', 'Frequenz: 5-55/min')
      frequency().should('have.prop', 'dualKnobs', true).scrollIntoView()
      frequency().shadow().find('[role="slider"]').should('have.length', 2).first().focus()
      pressKey('ArrowRight')
      pressKey('ArrowRight')
      frequencyTitle().should('have.text', 'Frequenz: 15-55/min')
      frequency().shadow().find('[role="slider"]').last().focus()
      for (let step = 0; step < 7; step++) pressKey('ArrowLeft')
      frequencyTitle().should('have.text', 'Frequenz: 15-20/min')
      frequency().should($range => {
        const rect = $range[0].getBoundingClientRect()
        expect(rect.left).to.be.at.least(0)
        expect(rect.right).to.be.at.most(320)
      })
      cy.screenshot(`ecg-frequency-${mode}-mobile`, { capture: 'viewport' })
      close()
      cy.get('#report').should('contain.text', 'EKG BAA; 15-20/min')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').click()
      frequencyTitle().should('have.text', 'Frequenz: 15-20/min')
      chip('Grundrhythmus', 'Herzstillstand').scrollIntoView().click()
      frequency().should('not.exist')
      modal().contains('ion-item-divider', 'Frequenz').should('not.exist')
      close()
      cy.get('#report').should('not.contain.text', '/min')
    })

    it('derives AV and ventricular knob modes from the selected subtype', () => {
      chip('Grundrhythmus', 'AV-Block').click()
      frequencyTitle().should('have.text', 'Frequenz: 60/min')
      frequency().should('have.prop', 'min', 5).and('have.prop', 'max', 300).and('have.prop', 'dualKnobs', false)
      for (const subtype of ['II. Grad Typ 1', 'II. Grad Typ 2']) {
        chip('Eingrenzen', subtype).scrollIntoView().click()
        frequencyTitle().should('have.text', 'Frequenz: 5-100/min')
        frequency().should('have.prop', 'dualKnobs', true).and('have.prop', 'max', 100)
      }
      chip('Eingrenzen', 'III. Grad').scrollIntoView().click()
      frequency().should('have.prop', 'dualKnobs', false).and('have.prop', 'max', 100)
      chip('Grundrhythmus', 'Kammerrhythmus').scrollIntoView().click()
      frequencyTitle().should('have.text', 'Frequenz: 60/min')
      chip('Eingrenzen', 'VT').click()
      frequencyTitle().should('have.text', 'Frequenz: 150/min')
      frequency().should('have.prop', 'dualKnobs', false).and('have.prop', 'min', 105)
      chip('Eingrenzen', 'Torsade de pointes').click()
      frequencyTitle().should('have.text', 'Frequenz: 105-300/min')
      frequency().should('have.prop', 'dualKnobs', true)
    })

    it('selects exclusively, preserves on close, and resets the entire examination', () => {
      chip('Grundrhythmus', 'Sinus').should('have.attr', 'aria-pressed', 'true')
      chip('Eingrenzen', 'Normo').should('have.attr', 'aria-pressed', 'true').click()
      group('Eingrenzen').find('[aria-pressed="true"]').should('not.exist')
      chip('Grundrhythmus', 'Vorhofflimmern').click()
      group('Grundrhythmus').find('[aria-pressed="true"]').should('have.length', 1)
      chip('Eingrenzen', 'Normo').should('have.attr', 'aria-pressed', 'true')
      chip('Eingrenzen', 'Tachy').click()
      chip('Extrasystolen', 'VES').click()
      chip('VES-Morphologie', 'Monomorph').click()
      close()
      cy.get('#report').should('contain.text', 'EKG TAA; monomorphe VES')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').click()
      chip('Eingrenzen', 'Tachy').should('have.attr', 'aria-pressed', 'true')
      close()
      cy.get('[data-examination="ecg"] .remove-examination').click()
      cy.get('#report').should('not.contain.text', 'EKG TAA')
      activate()
      chip('Grundrhythmus', 'Sinus').should('have.attr', 'aria-pressed', 'true')
      chip('Extrasystolen', 'Nein').should('have.attr', 'aria-pressed', 'true')
    })

    it('combines extrasystoles, evaluates Sgarbossa and clears hidden details', () => {
      chip('Extrasystolen', 'SVES').click()
      chip('Extrasystolen', 'VES').click()
      chip('Extrasystolen', 'Nein').should('have.attr', 'aria-pressed', 'false')
      chip('VES-Morphologie', 'Polymorph').click()
      chip('Schenkelblock', 'LSB').click()
      const criteria = () => modal().find('section[aria-label="Modifizierte Sgarbossa-Kriterien"]')
      criteria().find('ion-toggle').should('have.length', 3).each($toggle => {
        cy.wrap($toggle).should('have.prop', 'checked', false)
      })
      criteria().should('not.contain.text', 'Nicht beurteilt')
      criteria().find('[role="status"], .criterion-answer').should('not.exist')
      criteria().find('ion-toggle').eq(1).click()
      criteria().find('ion-toggle').eq(1).should('have.prop', 'checked', true)
      criteria().find('ion-toggle').eq(1).click()
      criteria().find('ion-toggle').each($toggle => {
        cy.wrap($toggle).should('have.prop', 'checked', false)
      })
      criteria().find('ion-toggle').eq(1).click()
      close()
      cy.get('#report').should('contain.text', 'LSB; Sgarbossa erfüllt (konk. ST-Senkung); SVES; polymorphe VES')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').click()
      chip('Schenkelblock', 'RSB').click()
      criteria().should('not.exist')
      chip('Schenkelblock', 'LSB').click()
      criteria().find('ion-toggle').each($toggle => {
        cy.wrap($toggle).should('have.prop', 'checked', false)
      })
      chip('Extrasystolen', 'Nein').click()
      group('VES-Morphologie').should('not.exist')
      close()
      cy.get('#report').should('contain.text', 'Sgarbossa negativ').and('not.contain.text', 'VES')
    })

    it('assigns separate ST leads and moves a lead when its direction changes', () => {
      modal().should('not.contain.text', 'Nicht beurteilbar')
      stSelect('Hebung').should('contain.text', 'Keine')
      stSelect('Senkung').should('contain.text', 'Keine')
      selectLeads('Hebung', ['II', 'III', 'aVF'])
      selectLeads('Senkung', ['V1', 'II'])
      stSelect('Hebung').click()
      leadChip('II').should('have.attr', 'aria-pressed', 'false')
      leadChip('V9r').scrollIntoView().click()
      applyLeads()
      stSelect('Hebung').should('contain.text', 'III, aVF, V9r')
      close()
      cy.get('#report').should('contain.text', 'hebt in III, aVF, V9r; senkt in II, V1')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').click()
      selectLeads('Senkung', ['II', 'V1'])
      stSelect('Senkung').should('contain.text', 'Keine')
      selectLeads('Hebung', ['III', 'aVF', 'V9r'])
      stSelect('Hebung').should('contain.text', 'Keine')
      close()
      cy.get('#report').should('not.contain.text', 'hebt').and('not.contain.text', 'senkt')
    })

    it('keeps chip rows on one line with bounded horizontal scrolling and semantic colors', () => {
      cy.viewport(320, 720)
      group('Grundrhythmus').find('.ecg-chip-row').should('have.length', 4)
      chip('Grundrhythmus', 'Sinus').should('have.css', 'background-color', 'rgb(45, 213, 91)')
      chip('Grundrhythmus', 'AV-Block').click().should('have.attr', 'aria-pressed', 'true')
      group('Eingrenzen').should($row => {
        expect($row[0].scrollWidth).to.be.greaterThan($row[0].clientWidth)
        const tops = Array.from($row[0].children).map(child => child.getBoundingClientRect().top)
        expect(new Set(tops).size).to.eq(1)
      })
      modal().find('.ecg-input').should($input => expect($input[0].getBoundingClientRect().width).to.be.at.most(320))
      chip('Eingrenzen', 'III. Grad').scrollIntoView().click()
      cy.screenshot(`ecg-${mode}-mobile`, { capture: 'viewport' })
      close()
      cy.get('#report').should('contain.text', 'AV-Block III°')
    })

    it('hides and clears inapplicable rhythm findings including their headings', () => {
      chip('Extrasystolen', 'SVES').click()
      chip('Extrasystolen', 'VES').click()
      chip('VES-Morphologie', 'Polymorph').click()
      chip('Schenkelblock', 'RSB').click()
      selectLeads('Hebung', ['II'])
      chip('Grundrhythmus', 'Vorhofflimmern').click()
      chip('Extrasystolen', 'SVES').should('not.exist')
      chip('Extrasystolen', 'VES').should('have.attr', 'aria-pressed', 'true')
      chip('Grundrhythmus', 'Vorhofflattern').click()
      chip('Extrasystolen', 'SVES').should('not.exist')
      chip('Grundrhythmus', 'Herzstillstand').click()
      chip('Eingrenzen', 'PEA').click()
      for (const label of ['Schenkelblock', 'Extrasystolen', 'ST-Strecke']) {
        group(label).should('not.exist')
        modal().contains('ion-item-divider', label).should('not.exist')
      }
      group('VES-Morphologie').should('not.exist')
      modal().find('section').should('not.exist')
      close()
      cy.get('#report').should('contain.text', 'EKG PEA').and('not.contain.text', 'VES')
        .and('not.contain.text', 'RSB').and('not.contain.text', 'hebt').and('not.contain.text', 'senkt')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').click()
      chip('Grundrhythmus', 'Kammerrhythmus').click()
      chip('Eingrenzen', 'VT').click()
      stSelect('Hebung').should('not.exist')
      group('Extrasystolen').should('not.exist')
      group('Schenkelblock').should('not.exist')
      chip('Grundrhythmus', 'Sinus').click()
      for (const label of ['Schenkelblock', 'Extrasystolen']) {
        chip(label, 'Nein').should('have.attr', 'aria-pressed', 'true')
      }
      stSelect('Hebung').should('contain.text', 'Keine')
      stSelect('Senkung').should('contain.text', 'Keine')
    })

    it('replaces ordinary ST entry only for LSB and clears old leads', () => {
      chip('Schenkelblock', 'RSB').click()
      selectLeads('Hebung', ['II'])
      chip('Schenkelblock', 'LSB').click()
      stSelect('Hebung').should('not.exist')
      modal().contains('ion-item-divider', 'ST-Strecke').should('not.exist')
      stSelect('Senkung').should('not.exist')
      modal().find('section[aria-label="Modifizierte Sgarbossa-Kriterien"]').should('exist')
      chip('Schenkelblock', 'RSB').click()
      stSelect('Hebung').should('contain.text', 'Keine')
      stSelect('Senkung').should('contain.text', 'Keine')
      close()
      cy.get('#report').should('contain.text', 'EKG SR; RSB').and('not.contain.text', 'hebt').and('not.contain.text', 'senkt')
    })

    it('distinguishes pacing types, preserves rate and resets Sgarbossa contexts', () => {
      const criteria = () => modal().find('section[aria-label="Modifizierte Sgarbossa-Kriterien"]')
      chip('Grundrhythmus', 'Schrittmacherrhythmus').click()
      chip('Eingrenzen', 'Tachy').click()
      chip('Stimulationsart', 'Nicht bestimmt').should('not.exist')
      chip('Stimulationsart', 'Ventrikulär / AV-sequenziell').should('have.attr', 'aria-pressed', 'true')
      group('Schenkelblock').should('not.exist')
      stSelect('Hebung').should('not.exist')
      criteria().find('ion-toggle').each($toggle => {
        cy.wrap($toggle).should('have.prop', 'checked', false)
      })
      chip('Stimulationsart', 'Nur atrial').click()
      stSelect('Hebung').should('exist')
      chip('Schenkelblock', 'LSB').click()
      criteria().find('ion-toggle').eq(0).click()
      chip('Stimulationsart', 'Ventrikulär / AV-sequenziell').scrollIntoView().click()
      chip('Eingrenzen', 'Tachy').should('have.attr', 'aria-pressed', 'true')
      group('Schenkelblock').should('not.exist')
      stSelect('Hebung').should('not.exist')
      chip('Extrasystolen', 'SVES').should('exist')
      chip('Extrasystolen', 'VES').should('exist')
      criteria().find('ion-toggle').each($toggle => {
        cy.wrap($toggle).should('have.prop', 'checked', false)
      })
      criteria().find('ion-toggle').eq(0).click()
      close()
      cy.get('#report').should('contain.text', 'EKG tachyk. Schrittmacherrhythmus; ventrikulär / AV-sequenziell stimuliert; Sgarbossa erfüllt (konk. ST-Hebung)')
        .and('not.contain.text', 'LSB')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').click()
      chip('Stimulationsart', 'Ventrikulär / AV-sequenziell').should('have.attr', 'aria-pressed', 'true')
      chip('Stimulationsart', 'Nur atrial').scrollIntoView().click()
      criteria().should('not.exist')
      chip('Schenkelblock', 'Nein').should('have.attr', 'aria-pressed', 'true')
      stSelect('Hebung').should('contain.text', 'Keine')
      stSelect('Senkung').should('contain.text', 'Keine')
      chip('Grundrhythmus', 'Sinus').click()
      group('Stimulationsart').should('not.exist')
      chip('Grundrhythmus', 'Schrittmacherrhythmus').click()
      chip('Stimulationsart', 'Ventrikulär / AV-sequenziell').should('have.attr', 'aria-pressed', 'true')
    })

    it('supports keyboard selection and restores focus when dismissed', () => {
      chip('Grundrhythmus', 'Vorhofflimmern').focus()
      pressKey('Enter')
      chip('Grundrhythmus', 'Vorhofflimmern').should('have.attr', 'aria-pressed', 'true').and('be.focused')
      chip('Eingrenzen', 'Tachy').focus()
      pressKey(' ')
      chip('Eingrenzen', 'Tachy').should('have.attr', 'aria-pressed', 'true').and('be.focused')
      pressKey('Escape')
      cy.get('ion-modal:visible').should('not.exist')
      cy.get('[data-examination="ecg"] .examination-control > ion-item').should($item => {
        const active = $item[0].ownerDocument.activeElement
        expect(active === $item[0] || $item[0].contains(active)).to.equal(true)
      })
    })
  })
}
