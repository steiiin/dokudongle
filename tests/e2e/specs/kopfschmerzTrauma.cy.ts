export {}

for (const width of [375, 1024]) {
  describe(`wound-localized headache at ${width}px`, () => {
    it('edits sides, course and severity with chips and selects', () => {
      cy.viewport(width, 900)
      cy.visit('/tests/e2e/fixtures/examination.html?disability&shortcuts')
      cy.get('[data-block-source="kopfschmerz"]').scrollIntoView().click()
      cy.contains('ion-modal:visible', 'Seit wann?').should('not.exist')
      cy.contains('ion-modal:visible', 'Begleitsymptome').should('not.exist')
      cy.contains('ion-modal:visible ion-select', 'Beginn').click()
      cy.contains('ion-popover:visible ion-item', 'Schlagartig').click()
      cy.contains('ion-modal:visible ion-select', '↳ Schmerzmaximum').should('contain.text', 'Sofort').click()
      cy.contains('ion-popover:visible', 'Keine Angabe').should('not.exist')
      cy.contains('ion-popover:visible ion-item', '<5min').click()
      cy.get('#report').should('contain.text', 'Schmerzmaximum innerhalb von 5 Minuten erreicht')
      cy.contains('ion-modal:visible ion-chip', 'Links').scrollIntoView().should('have.attr', 'color', 'warning').click()
      cy.contains('ion-modal:visible ion-chip', 'Rechts').click()
      cy.contains('ion-modal:visible ion-chip', 'Links').should('not.exist')
      cy.contains('ion-modal:visible ion-chip', 'Rechts').should('not.exist')
      cy.contains('ion-modal:visible ion-chip', 'Beidseits').should('have.attr', 'color', 'success')
        .and('have.class', 'DdToggleChip--bold')
      cy.contains('ion-modal:visible ion-chip', 'hinter dem Auge').click()
      cy.get('#report').should('contain.text', 'beidseits hinter den Augen')
      cy.contains('ion-modal:visible ion-chip', 'Beidseits').click()
      cy.contains('ion-modal:visible ion-chip', 'Links').should('have.class', 'DdToggleChip--inactive')
      cy.contains('ion-modal:visible ion-select', 'Schmerzen').scrollIntoView().click()
      cy.contains('ion-popover:visible ion-item', 'Stark (7-8)').click()
      cy.contains('ion-modal:visible ion-chip', 'Zunehmend').scrollIntoView().should('have.attr', 'color', 'primary').click()
      cy.contains('ion-modal:visible ion-chip', 'Abnehmend').should('not.exist')
      cy.contains('ion-modal:visible ion-chip', 'Gleichbleibend').should('not.exist')
      cy.contains('ion-modal:visible ion-chip', 'Anhaltend').should('have.attr', 'color', 'success').click()
      cy.contains('ion-modal:visible ion-chip', 'Attackenartig').should('not.exist')
      cy.get('#report').should('contain.text', 'stark; zunehmend, anhaltend')
      cy.contains('ion-modal:visible ion-chip', 'Zunehmend').click()
      cy.contains('ion-modal:visible ion-chip', 'Abnehmend').should('be.visible')
      cy.contains('ion-modal:visible ion-chip', 'Gleichbleibend').should('be.visible')
      cy.contains('ion-modal:visible ion-chip', 'Anhaltend').click()
      cy.contains('ion-modal:visible ion-chip', 'Attackenartig').should('be.visible')
    })

    it('shares the yellow trauma chip with the SHT output and excludes other locations', () => {
      cy.viewport(width, 900)
      cy.visit('/tests/e2e/fixtures/examination.html?disability&shortcuts&trauma')
      cy.get('[data-block-source="kopfschmerz"]').scrollIntoView().click()
      cy.contains('ion-modal:visible ion-chip', 'Im Wundbereich').should('have.attr', 'color', 'warning')
      cy.get('#report').should('contain.text', 'Kopf: Kopfschmerzen - mgl. SHT.')
      cy.contains('ion-modal:visible ion-chip', 'Stirn').scrollIntoView().click()
      cy.contains('ion-modal:visible ion-chip', 'Im Wundbereich').click()
      cy.contains('ion-modal:visible ion-chip', 'Stirn').should('have.class', 'DdToggleChip--inactive')
      cy.get('#report').should('contain.text', 'im Wundbereich')
        .and('contain.text', 'Schmerzen nur im Wundbereich - SHT unwahrsch')
      cy.contains('ion-modal:visible ion-chip', 'Gesamter Kopf').click()
      cy.contains('ion-modal:visible ion-chip', 'Im Wundbereich').should('not.exist')
      for (const label of ['Links', 'Rechts', 'Stirn', 'Schläfe', 'Hinterkopf', 'hinter dem Auge']) {
        cy.contains('ion-modal:visible ion-chip', label).should('not.exist')
      }
      cy.get('#report').should('contain.text', 'Kopf: Kopfschmerzen - mgl. SHT.')
        .and('not.contain.text', 'Wundbereich')
      cy.get('ion-modal:visible ion-button[title="Zurück"]').click()
      cy.contains('#original-block-forms ion-item', 'Kopfschmerzen').scrollIntoView().click()
      cy.contains('ion-modal:visible ion-chip', 'Gesamter Kopf').should('have.class', 'DdToggleChip--bold').click()
      cy.contains('ion-modal:visible ion-chip', 'Links').should('have.class', 'DdToggleChip--inactive')
      cy.contains('ion-modal:visible ion-chip', 'Im Wundbereich').click().click()
      cy.get('#report').should('contain.text', 'Kopf: Kopfschmerzen - mgl. SHT.')
        .and('not.contain.text', 'Wundbereich')

      cy.visit('/tests/e2e/fixtures/examination.html?disability&shortcuts')
      cy.get('[data-block-source="kopfschmerz"]').scrollIntoView().click()
      cy.contains('ion-modal:visible ion-chip', 'Im Wundbereich').should('not.exist')
    })
  })
}
