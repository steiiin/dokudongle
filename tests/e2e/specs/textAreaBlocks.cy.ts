const clickVisible = (selector: string, text: string) => cy.contains(selector, text)
  .then($element => $element[0].scrollIntoView({ block: 'center' }))
  .click({ scrollBehavior: false })

const sourceInput = (label: string) => cy.get('ion-input')
  .filter((_index, element) => (element as HTMLElement & { label?: string }).label === label).find('input')
const fillSource = (label: string, value: string) => sourceInput(label)
  .should($input => expect($input[0].hasAttribute('readonly')).to.eq(false))
  .then($input => $input[0].scrollIntoView({ block: 'center' }))
  .clear({ scrollBehavior: false }).type(value, { scrollBehavior: false })

describe('Generated Situation blocks', () => {
  beforeEach(() => {
    cy.then(() => Cypress.automation('remote:debugger:protocol', {
      command: 'Storage.clearDataForOrigin',
      params: { origin: new URL(Cypress.config('baseUrl')!).origin, storageTypes: 'all' },
    }))
  })
  it('updates, deactivates, restores and clears source data while preserving manual text', () => {
    cy.viewport(375, 812)
    cy.visit('/tabs/doku')
    clickVisible('ion-chip', 'Verlegung')
    fillSource('START', 'Radebeul')
    cy.get('.dd-input-preview .dd-textarea-block').should('not.exist')
    fillSource('ZIEL', 'Dresden')
    cy.get('.dd-input-preview .preview').should('have.text', 'Verlegung von Radebeul nach Dresden.')
    cy.get('.dd-input-preview .dd-textarea-block').should('not.exist')
    fillSource('ZIEL', 'Coswig')
    cy.get('.dd-input-preview .preview').should('have.text', 'Verlegung von Radebeul nach Coswig.')
    clickVisible('ion-button', 'Situation')
    cy.get('.dd-modal-blocks').should('contain.text', 'Verlegung von Radebeul nach Coswig.')
    cy.get<HTMLTextAreaElement>('textarea.dd-modal-textarea')
      .should('have.value', '').and($input => expect($input[0].hasAttribute('readonly')).to.eq(false)).type('Eigener Text')
    cy.get('.dd-modal-blocks button').focus().should('have.focus').type('{enter}')
    cy.get('.dd-modal-blocks .dd-textarea-block').should('have.class', 'is-inactive').and('have.attr', 'aria-pressed', 'false')
    cy.get('ion-modal:visible ion-button[title="Zurück"]').click()
    cy.get('.dd-input-preview .preview').should('have.text', 'Eigener Text')
    clickVisible('ion-tab-button', 'Vorschau')
    cy.get('textarea:visible').should('contain.value', 'Eigener Text').and('not.contain.value', 'Verlegung von')
    clickVisible('ion-tab-button', 'Eingabe')
    clickVisible('ion-button', 'Situation')
    clickVisible('.dd-modal-blocks .dd-textarea-block-text', 'Verlegung von Radebeul nach Coswig.')
    cy.get('.dd-modal-blocks .dd-textarea-block').should('have.attr', 'aria-pressed', 'true')
    cy.get('ion-modal:visible ion-button[title="Zurück"]').click()
    cy.get('.dd-input-preview .preview').should('have.text', 'Verlegung von Radebeul nach Coswig.\nEigener Text')
    clickVisible('ion-tab-button', 'Vorschau')
    cy.get('textarea:visible').should('contain.value', 'Verlegung von Radebeul nach Coswig.\nEigener Text')
    clickVisible('ion-tab-button', 'Eingabe')
    clickVisible('ion-chip', 'Verlegung')
    cy.get('.dd-textarea-block').should('not.exist')
    clickVisible('ion-chip', 'Verlegung')
    sourceInput('START').should('have.value', '')
    sourceInput('ZIEL').should('have.value', '')
    cy.get('.dd-input-preview').should('contain.text', 'Eigener Text')
  })

  it('keeps the editor scrollable and blocks readable with mobile keyboard-sized space', () => {
    cy.viewport(375, 812)
    cy.visit('/tabs/doku')
    clickVisible('ion-chip', 'Einweisung')
    fillSource('ARZT', 'HA Wegner')
    fillSource('ZIEL', 'FKH Coswig')
    fillSource('KRANKHEIT', 'Thrombose')
    clickVisible('ion-button', 'Situation')
    cy.get<HTMLTextAreaElement>('textarea.dd-modal-textarea').should($input => expect($input[0].hasAttribute('readonly')).to.eq(false))
      .type('12345{enter}'.repeat(40), { delay: 0 })
    cy.viewport(375, 480)
    cy.get<HTMLTextAreaElement>('textarea.dd-modal-textarea').should($textarea => {
      const textarea = $textarea[0]
      expect(textarea.clientHeight).to.be.greaterThan(40)
      expect(textarea.scrollHeight).to.be.greaterThan(textarea.clientHeight)
      const footer = textarea.closest('ion-modal')!.querySelector('ion-footer')!
      expect(textarea.getBoundingClientRect().bottom).to.be.at.most(footer.getBoundingClientRect().top)
    })
    cy.get('.dd-modal-blocks .dd-textarea-block').should('be.visible').and('contain.text', 'Thrombose')
    cy.get('.dd-modal-blocks button').should('be.visible')
    cy.screenshot('generated-blocks-mobile-dark')
    // The app uses Ionic's always-dark palette; also exercise the component with light theme tokens.
    cy.get('.dd-modal-data').invoke('attr', 'style', '--ion-background-color: #fff; --ion-text-color: #222; background: #fff; color: #222;')
    cy.get('.dd-modal-blocks .dd-textarea-block').should('have.css', 'color', 'rgb(34, 34, 34)')
    cy.screenshot('generated-blocks-mobile-light-tokens')
  })
})
